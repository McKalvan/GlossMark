// @gloss implements gmi:AgentsSnippet scope=file

// Package agents generates the AGENTS.md vocabulary snippet: the concepts an
// agent may link to in a boundary, before it writes code.
package agents

import (
	"fmt"
	"sort"
	"strings"

	"github.com/mckalvan/glossmark/internal/graph"
	"github.com/mckalvan/glossmark/internal/load"
	"github.com/mckalvan/glossmark/internal/model"
)

// Snippet renders the vocabulary for one manifest (or the whole repo when m is nil).
func Snippet(ws *load.Workspace, g *graph.Graph, m *model.Manifest) string {
	var sb strings.Builder
	sb.WriteString("<!-- generated by gloss agents; do not edit by hand -->\n")
	sb.WriteString("## GlossMark vocabulary\n\n")
	sb.WriteString("Link what you write to the ontology with one comment line per declaration, in the file's own comment syntax:\n\n")
	sb.WriteString("```\n@gloss[?] <relation> <target>[, <target>...] [scope=file|symbol|block|line|range] [conf=0.0-1.0] [id=<stable-id>] [note=\"...\"]\n```\n\n")
	sb.WriteString("- Write `@gloss?` for links you are proposing; a human accepts them with `gloss accept`. Never write a bare `@gloss` for a link you are not sure of.\n")
	sb.WriteString("- " + ProposalSentence + "\n")
	sb.WriteString("- Relations you may use inline: ")
	sb.WriteString(RelationGuidance(ws) + "\n")
	if m != nil {
		fmt.Fprintf(&sb, "- This directory is boundary `%s` (%s)", m.Boundary, m.Level)
		if m.DefaultNamespace != "" {
			fmt.Fprintf(&sb, "; `.Name` resolves to `%s:Name`", m.DefaultNamespace)
		}
		sb.WriteString(".\n")
		if len(m.Allowed) > 0 {
			fmt.Fprintf(&sb, "- Allowed targets here: %s. Links outside this list are HARD-gated.\n", codeList(m.Allowed))
		}
	}
	sb.WriteString("\n### Concepts\n\n")
	// Group by namespace, core first.
	nss := map[string][]*graph.Node{}
	for _, n := range g.NodesOf(model.NodeConcept) {
		if n.Deprecated {
			continue
		}
		if n.Imported && n.Tier == model.TierImpl && n.Published == "" {
			continue
		}
		if m != nil && len(m.Allowed) > 0 && !model.MatchAnyCurie(m.Allowed, n.CURIE) {
			continue
		}
		nss[n.NS] = append(nss[n.NS], n)
	}
	order := make([]string, 0, len(nss))
	for ns := range nss {
		order = append(order, ns)
	}
	sort.Slice(order, func(i, j int) bool {
		ti, tj := ws.Tier(order[i]), ws.Tier(order[j])
		if ti != tj {
			return ti == model.TierCore
		}
		return order[i] < order[j]
	})
	for _, ns := range order {
		fmt.Fprintf(&sb, "**%s:** (%s", ns, ws.Tier(ns))
		if im, ok := ws.Imported[ns]; ok {
			fmt.Fprintf(&sb, ", imported %s", im.Version)
		}
		sb.WriteString(")\n\n| Concept | Kind | Criticality | Notes |\n| --- | --- | --- | --- |\n")
		for _, n := range nss[ns] {
			var notes []string
			if n.Proposed {
				// Tagged as gloss context tags it: linkable, but HARD-gated
				// until a human accepts the concept.
				notes = append(notes, "PROPOSED")
			}
			if n.Planned {
				// Specified, not built: the name to link the feature to.
				notes = append(notes, plannedTag(n))
			}
			if n.Doc != "" {
				// The notes are joined with "; ", so a doc's own full stop
				// would read ".; realizes".
				notes = append(notes, strings.TrimRight(strings.TrimSpace(n.Doc), "."))
			}
			for _, r := range g.Objects(n.ID, "realizes") {
				notes = append(notes, "realizes "+g.Curie(r))
			}
			for _, r := range g.Objects(n.ID, "is-a") {
				notes = append(notes, "is-a "+g.Curie(r))
			}
			if n.Published != "" {
				notes = append(notes, "published as "+n.Published)
			}
			if n.Internal {
				notes = append(notes, "internal")
			}
			if len(n.Aliases) > 0 {
				notes = append(notes, "aka "+strings.Join(n.Aliases, "/"))
			}
			fmt.Fprintf(&sb, "| `%s` | %s | %s | %s |\n", n.CURIE, n.Kind, n.Criticality, strings.Join(notes, "; "))
		}
		sb.WriteString("\n")
	}
	return sb.String()
}

// RelationGuidance is the sentence that lists the inline relations an agent
// may write and what each is for, under the repository's relation profile
// (glossmark.yaml relations:, issue #261): the starter list names the switch
// to the rest, the full list the IaC, config and CI relations. The snippet
// and the MCP server's instructions share it. tests is the accepted alias of
// verifies that check asks to replace (GM240), so neither names it.
func RelationGuidance(ws *load.Workspace) string {
	profile := ws.Config.RelationProfile()
	var inl []string
	for _, r := range ws.Vocab.InlineNames(profile) {
		inl = append(inl, "`"+r+"`")
	}
	s := strings.Join(inl, ", ")
	if profile == model.ProfileStarter {
		return s + ". Use `implements` for behaviour, `represents` for data shapes, `verifies` in tests, `produces`/`consumes` for what code emits and reads. This repository uses the starter relation profile; the rest (`presents`, `hosts`, `configures`, `documents`, ...) need `relations: full` in " + load.ConfigName + "."
	}
	return s + ". Use `implements` for behaviour, `represents` for data shapes, `verifies` in tests, `provisions`/`configures`/`deploys` in IaC, config and CI."
}

func codeList(xs []string) string {
	var out []string
	for _, x := range xs {
		out = append(out, "`"+x+"`")
	}
	return strings.Join(out, ", ")
}
