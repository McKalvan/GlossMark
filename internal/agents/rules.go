// The rules block is the behaviour every agent in a GlossMark repository
// follows, whatever the directory. It is rendered from the constants below
// into AGENTS.md (gloss agents --rules, gloss init), checked by gloss doctor,
// and quoted by the MCP server's instructions, so every copy says the same.
const (
	// RulesBegin opens the rules block in AGENTS.md.
	RulesBegin = "<!-- gloss:rules:begin (generated by gloss agents --rules; do not edit by hand) -->"
	// RulesEnd closes it.
	RulesEnd = "<!-- gloss:rules:end -->"
	// rulesBeginPrefix finds a rules block whatever its begin comment says,
	// so a block written by an older release is still replaced.
	rulesBeginPrefix = "<!-- gloss:rules:begin"
	// RulesHeading is the block's heading.
	RulesHeading = "## GlossMark"
	// RulesIntro says what the repository does and when the rules apply.
	RulesIntro = "This repository links code to its domain ontology with one-line `@gloss` comments, and `gloss` checks them. These rules apply whenever you add, change, move or delete code, tests, docs, infrastructure, config, CI or agent files."
	// RulesDocURL is where the rules are explained for the people setting up an agent.
	RulesDocURL = "https://github.com/mckalvan/glossmark/blob/main/docs/AGENT-HARNESS.md"
)

