// RuleSkills are the shipped skills the rules block points to for longer tasks.
var RuleSkills = []string{"gloss-link", "gloss-resolve-drift", "gloss-review", "adopt-glossmark"}

// knownSkills are every GlossMark skill name the briefing looks for under
// .claude/skills/: the shipped ones, the ones the rules name, and the ones
// planned for criticality and imports.
func knownSkills() []string {
	seen := map[string]bool{}
	var out []string
	for _, group := range [][]string{RuleSkills, skills.Names, {"gloss-criticality", "gloss-upgrade-import"}} {
		for _, n := range group {
			if !seen[n] {
				seen[n] = true
				out = append(out, n)
			}
		}
	}
	return out
}

// mcpRules are the rules the MCP server states in its instructions: the
// ones about the briefing, finding and proposing targets, the proposal
// workflow and reporting what a change touches.
var mcpRules = []int{0, 2, 3, 4, 7}

// RulesBlock renders the rules block, from RulesBegin to RulesEnd, without a
// trailing newline.
func RulesBlock() string {
	var sb strings.Builder
	sb.WriteString(RulesBegin + "\n")
	sb.WriteString(RulesHeading + "\n\n")
	sb.WriteString(RulesIntro + "\n\n")
	for i, r := range Rules {
		fmt.Fprintf(&sb, "%d. %s\n", i+1, r)
	}
	sb.WriteString("\nWorkflows for longer tasks: skills ")
	sb.WriteString(codeList(RuleSkills))
	sb.WriteString(". Rule details: " + RulesDocURL + "\n")
	sb.WriteString(RulesEnd)
	return sb.String()
}

// MCPInstructions is the MCP server's instructions: the rules that concern
// its tools, in the rules block's words without the Markdown emphasis.
func MCPInstructions() string {
	parts := []string{"GlossMark serves this repository's code ontology."}
	for _, i := range mcpRules {
		parts = append(parts, strings.ReplaceAll(Rules[i], "**", ""))
	}
	return strings.Join(parts, " ")
}

// FindRules returns the byte range of the rules block in doc, from its begin
// comment to the end of RulesEnd. ok is false when there is no begin comment;
// err is set when there is a begin comment without an end after it.
func FindRules(doc string) (start, end int, ok bool, err error) {
	i := strings.Index(doc, rulesBeginPrefix)
	if i < 0 {
		return 0, 0, false, nil
	}
	j := strings.Index(doc[i:], RulesEnd)
	if j < 0 {
		return 0, 0, false, fmt.Errorf("%s without %s; fix the file by hand", rulesBeginPrefix+" -->", RulesEnd)
	}
	return i, i + j + len(RulesEnd), true, nil
}

// RulesStatus is the state of the rules block in a document.
type RulesStatus int

const (
	RulesMissing RulesStatus = iota
	RulesStale
	RulesCurrent
)

// CheckRules reports whether doc holds the current rules block.
func CheckRules(doc string) (RulesStatus, error) {
	i, j, ok, err := FindRules(doc)
	if err != nil {
		return RulesStale, err
	}
	if !ok {
		return RulesMissing, nil
	}
	if doc[i:j] != RulesBlock() {
		return RulesStale, nil
	}
	return RulesCurrent, nil
}

// UpsertRules returns doc with the rules block replaced by the current one,
// or appended after a blank line when doc has none. Text outside the block,
// including a gloss:begin/gloss:end vocabulary block, is kept byte for byte.
func UpsertRules(doc string) (string, error) {
	i, j, ok, err := FindRules(doc)
	if err != nil {
		return "", err
	}
	if ok {
		return doc[:i] + RulesBlock() + doc[j:], nil
	}
	return doc + AppendRules(doc), nil
}

// AppendRules is the text to add to the end of doc, which has no rules
// block, to give it one.
func AppendRules(doc string) string {
	if doc == "" {
		return RulesBlock() + "\n"
	}
	pre := "\n"
	if !strings.HasSuffix(doc, "\n") {
		pre = "\n\n"
	}
	return pre + RulesBlock() + "\n"
}

// ClaudeImport is the line in CLAUDE.md that makes Claude Code read AGENTS.md.
const ClaudeImport = "@AGENTS.md"

// HasClaudeImport reports whether a CLAUDE.md imports AGENTS.md on a line of its own.
func HasClaudeImport(doc string) bool {
	for _, l := range strings.Split(doc, "\n") {
		if strings.TrimSpace(l) == ClaudeImport {
			return true
		}
	}
	return false
}

// InstalledSkills lists the GlossMark skills installed in the repository at
// root (.claude/skills/<name>/SKILL.md), sorted.
func InstalledSkills(root string) []string {
	var out []string
	for _, n := range knownSkills() {
		if _, err := os.Stat(filepath.Join(root, ".claude", "skills", n, "SKILL.md")); err == nil {
			out = append(out, n)
		}
	}
	sort.Strings(out)
	return out
}
