// vocabularySection wraps the AGENTS.md snippet between markers, so a rerun
// replaces it and a hand-written rule around it survives.
func vocabularySection(snippet string) string {
	return vocabularyBegin + "\n" + strings.TrimSpace(snippet) + "\n" + vocabularyEnd + "\n"
}

// replaceSection replaces the text between begin and end (inclusive) in doc
// with section, or appends section when the markers are not there.
func replaceSection(doc, begin, end, section string) string {
	i := strings.Index(doc, begin)
	j := strings.Index(doc, end)
	if i >= 0 && j > i {
		j += len(end)
		if j < len(doc) && doc[j] == '\n' {
			j++
		}
		return doc[:i] + section + doc[j:]
	}
	if doc != "" && !strings.HasSuffix(doc, "\n") {
		doc += "\n"
	}
	if doc != "" {
		doc += "\n"
	}
	return doc + section
}

// registerMCPIn adds the glossmark server to an MCP config file (rel to
// root) whose server map is under key. extra fields are set on the entry
// (VS Code wants "type": "stdio"). The file is committed, so the server
// runs gloss by name; a path an earlier install wrote is replaced, a
// command of the user's own is kept. quiet skips the per-file line.
func registerMCPIn(root, rel, key, actor string, extra map[string]any, quiet bool) error {
	path := filepath.Join(root, filepath.FromSlash(rel))
	cfg := map[string]any{}
	if b, err := os.ReadFile(path); err == nil {
		json.Unmarshal(b, &cfg)
	}
	servers, _ := cfg[key].(map[string]any)
	if servers == nil {
		servers = map[string]any{}
	}
	srv, _ := servers[pluginName].(map[string]any)
	if srv == nil {
		srv = map[string]any{"args": []string{"mcp"}}
	}
	if c, _ := srv["command"].(string); c == "" || strings.HasPrefix(filepath.Base(c), "gloss") {
		srv["command"] = "gloss"
	}
	keys := make([]string, 0, len(extra))
	for k := range extra {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		srv[k] = extra[k]
	}
	env, _ := srv["env"].(map[string]any)
	if env == nil {
		env = map[string]any{}
	}
	env["GLOSS_ACTOR"] = actor
	srv["env"] = env
	servers[pluginName] = srv
	cfg[key] = servers
	if err := writeJSON(path, cfg); err != nil {
		return err
	}
	if !quiet {
		fmt.Printf("gloss hook: MCP server registered in %s\n", relOrAbs(root, path))
	}
	return nil
}
