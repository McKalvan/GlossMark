// copilotSection is the GlossMark section of .github/copilot-instructions.md.
// Copilot has no session hook and no plugin, so the instructions carry what
// the briefing would say and point at the MCP server for the rest.
func copilotSection(actor string) string {
	a := shellWord(actor)
	return copilotBegin + `
## GlossMark

This repository links code to a domain ontology with one-line ` + "`@gloss`" + ` comments (see the vocabulary below).

- Before editing a file, ask the ` + "`glossmark`" + ` MCP server (` + "`.vscode/mcp.json`" + `) ` + "`concepts_for_path`" + ` for the concepts that path may link to, or run ` + "`gloss context --dir <its directory> --changed --budget 2000`" + ` and read the briefing: the boundary, the allowed targets, the current state.
- Run every gloss command as ` + "`GLOSS_ACTOR=" + a + " gloss ...`" + ` so the links you write are attributed to you; the MCP server already runs as that actor.
- Write ` + "`@gloss?`" + ` (with the question mark) on every declaration you add or change; a human accepts it with ` + "`gloss accept`" + ` or over ` + "`gloss review`" + `. Never write a bare ` + "`@gloss`" + ` for a link you are not sure of.
- ` + agents.ProposalSentence + `
- Use ` + "`search_concepts`" + `, ` + "`concepts_for_path`" + `, ` + "`propose_link`" + `, ` + "`propose_concept`" + `, ` + "`impact_of`" + `, ` + "`slice_of`" + ` and ` + "`history_of`" + ` on the MCP server; ` + "`gloss check`" + ` and ` + "`gloss drift`" + ` before you open a pull request.
- The skills in ` + "`.claude/skills/`" + ` (` + "`gloss hook install --skill`" + `) describe adopting GlossMark, deriving the ontology, reviewing the queue and planning a feature in the ontology first: follow the one that matches what you are asked. The ontology is the owner's; interview them before writing an ontology file, and stop and wait for their answers.
` + copilotEnd + "\n"
}

// installCopilotInstructions writes the GlossMark section into the
// repository's Copilot instructions, keeping whatever else the file says.
// snippet is the AGENTS.md vocabulary for the whole repository ("" before
// gloss init). The MCP server goes to .vscode/mcp.json, the file VS Code
// reads, through registerMCPIn.
func installCopilotInstructions(root, actor, snippet string) error {
	path := filepath.Join(root, filepath.FromSlash(copilotPath))
	old, _ := os.ReadFile(path)
	section := copilotSection(actor)
	if snippet != "" {
		section = strings.TrimSuffix(section, copilotEnd+"\n") + "\n" + vocabularySection(snippet) + copilotEnd + "\n"
	}
	out := replaceSection(string(old), copilotBegin, copilotEnd, section)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(out), 0o644); err != nil {
		return err
	}
	fmt.Printf("gloss hook: Copilot instructions written to %s (the GlossMark section; the rest of the file is kept)\n", copilotPath)
	return nil
}

