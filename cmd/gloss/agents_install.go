// Ready-made agent integrations (issue #267): gloss hook install --agent
// writes, for one agent, everything that agent needs to call
// concepts_for_path before it edits and to write proposal markers. Every
// file is committed, so each names gloss by its bare name (issue #226);
// nothing here ever writes this machine's binary path.
//
//	claude-code  a Claude Code plugin in .claude/plugins/glossmark (manifest,
//	             the four skills, a SessionStart hook, the MCP server) and a
//	             marketplace entry at .claude-plugin/marketplace.json, so one
//	             command installs it
//	cursor       .cursor/rules/glossmark.mdc (always applied, with the
//	             AGENTS.md vocabulary) and .cursor/mcp.json
//	copilot      .github/copilot-instructions.md (a GlossMark section with
//	             the vocabulary) and .vscode/mcp.json
//
// The flag is the one way to ask; --cursor stays as the short form of
// --agent cursor.
var agentNames = []string{"claude-code", "cursor", "copilot"}

// defaultActors are the GLOSS_ACTOR each integration runs as unless --actor
// is given, so links an agent writes name the agent that wrote them.
var defaultActors = map[string]string{"claude-code": "agent:claude-code", "cursor": "agent:cursor", "copilot": "agent:copilot"}

// Where each integration lives, relative to the root. The doctor reads the
// same paths.
const (
	pluginDir         = ".claude/plugins/glossmark"
	marketplacePath   = ".claude-plugin/marketplace.json"
	copilotPath       = ".github/copilot-instructions.md"
	vscodeMCPPath     = ".vscode/mcp.json"
	pluginName        = "glossmark"
	vocabularyBegin   = "<!-- gloss agents: begin (generated; gloss hook install rewrites this section) -->"
	vocabularyEnd     = "<!-- gloss agents: end -->"
	copilotBegin      = "<!-- glossmark: begin (generated by gloss hook install --agent copilot; rerun it to update) -->"
	copilotEnd        = "<!-- glossmark: end -->"
	marketplaceSuffix = "-plugins"
)

// parseAgents validates the --agent values: one name per flag or a
// comma-separated list, each one of agentNames, in the order given.
func parseAgents(values []string) ([]string, error) {
	var out []string
	seen := map[string]bool{}
	for _, v := range values {
		for _, a := range strings.Split(v, ",") {
			a = strings.TrimSpace(a)
			if a == "" {
				continue
			}
			known := false
			for _, n := range agentNames {
				known = known || n == a
			}
			if !known {
				return nil, fmt.Errorf("--agent %s: unknown agent; one of %s", a, strings.Join(agentNames, ", "))
			}
			if !seen[a] {
				seen[a] = true
				out = append(out, a)
			}
		}
	}
	return out, nil
}

