// pluginManifest is .claude-plugin/plugin.json inside the plugin: the fields
// Claude Code reads (name is the only required one) plus the metadata
// /plugin shows. Skills, hooks and the MCP server sit in their default
// locations, so the manifest does not list them.
func pluginManifest() map[string]any {
	return map[string]any{
		"name":        pluginName,
		"version":     version.String(),
		"description": "GlossMark: the domain ontology this repository's code links to with @gloss comments. Brief at session start, concept search and proposals over MCP, and the adopt, derive, review and curate skills.",
		"author":      map[string]any{"name": "GlossMark", "url": "https://github.com/mckalvan/glossmark"},
		"homepage":    "https://github.com/mckalvan/glossmark/blob/main/docs/AGENTS.md",
		"repository":  "https://github.com/mckalvan/glossmark",
		"license":     "MIT",
		"keywords":    []string{"glossmark", "ontology", "domain-model", "mcp"},
	}
}

// pluginHooks is hooks/hooks.json: the same SessionStart hook gloss hook
// install puts in .claude/settings.json, wrapped the way a plugin hooks file
// is. It runs gloss by name; a plugin is installed into Claude Code's cache,
// so no path in it may name this repository or this machine.
func pluginHooks(actor string) map[string]any {
	return map[string]any{"hooks": map[string]any{"SessionStart": []any{
		map[string]any{"hooks": []any{map[string]any{"type": "command", "command": hookCommand(actor, "gloss")}}},
	}}}
}

// installClaudePlugin writes the plugin and lists it in the repository's
// marketplace file. It rewrites what it owns (manifest, hooks, MCP config,
// the shipped skills) and leaves any other file in the plugin directory
// alone, so a team can add its own agents or skills beside them.
func installClaudePlugin(root, actor string) error {
	dir := filepath.Join(root, filepath.FromSlash(pluginDir))
	if err := writeJSON(filepath.Join(dir, ".claude-plugin", "plugin.json"), pluginManifest()); err != nil {
		return err
	}
	if err := writeJSON(filepath.Join(dir, "hooks", "hooks.json"), pluginHooks(actor)); err != nil {
		return err
	}
	for _, name := range skills.Names {
		b, err := skills.Installable(name)
		if err != nil {
			return err
		}
		path := filepath.Join(dir, "skills", name, "SKILL.md")
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, b, 0o644); err != nil {
			return err
		}
	}
	if err := registerMCPIn(root, filepath.ToSlash(filepath.Join(pluginDir, ".mcp.json")), "mcpServers", actor, nil, true); err != nil {
		return err
	}
	market, err := registerMarketplace(root)
	if err != nil {
		return err
	}
	fmt.Printf("gloss hook: Claude Code plugin written to %s (manifest, %d skills, SessionStart hook, MCP server) and listed in %s\n", pluginDir, len(skills.Names), marketplacePath)
	fmt.Printf("gloss hook: install it for everyone on this repository with: claude plugin marketplace add ./ && claude plugin install %s@%s --scope project\n", pluginName, market)
	fmt.Printf("gloss hook: or load it for one session with: claude --plugin-dir %s\n", pluginDir)
	return nil
}

// marketplaceName derives the name of the repository's marketplace from its
// directory: letters, digits, dots, underscores and dashes, starting with a
// letter or digit, as Claude Code requires of a name a user types after @.
func marketplaceName(root string) string {
	base := strings.ToLower(filepath.Base(root))
	base = regexp.MustCompile(`[^a-z0-9._-]+`).ReplaceAllString(base, "-")
	base = strings.Trim(base, "-._")
	if base == "" || base == "." {
		base = "repo"
	}
	return base + marketplaceSuffix
}

// registerMarketplace lists the plugin in .claude-plugin/marketplace.json at
// the root, creating the file or adding the entry to one the repository
// already keeps for its own plugins (the name and owner there are kept).
// It returns the marketplace name an install command uses.
func registerMarketplace(root string) (string, error) {
	path := filepath.Join(root, filepath.FromSlash(marketplacePath))
	m := map[string]any{}
	if b, err := os.ReadFile(path); err == nil {
		json.Unmarshal(b, &m)
	}
	name, _ := m["name"].(string)
	if name == "" {
		name = marketplaceName(root)
		m["name"] = name
	}
	if _, ok := m["owner"].(map[string]any); !ok {
		m["owner"] = map[string]any{"name": filepath.Base(root)}
	}
	if _, ok := m["description"].(string); !ok {
		m["description"] = "Plugins this repository ships; gloss hook install --agent claude-code maintains the glossmark entry"
	}
	entry := map[string]any{
		"name":        pluginName,
		"source":      "./" + pluginDir,
		"description": "GlossMark: session-start briefing, MCP concept tools and the adoption skills for this repository's ontology",
		"version":     version.String(),
	}
	plugins, _ := m["plugins"].([]any)
	list := []any{}
	replaced := false
	for _, p := range plugins {
		if pm, _ := p.(map[string]any); pm != nil && pm["name"] == pluginName {
			if !replaced {
				list = append(list, entry)
			}
			replaced = true
			continue
		}
		list = append(list, p)
	}
	if !replaced {
		list = append(list, entry)
	}
	m["plugins"] = list
	return name, writeJSON(path, m)
}

